package com.fleet.storefront.application.port.in;

import com.fleet.storefront.domain.catalog.Sku;
import com.fleet.storefront.domain.order.Quantity;
import com.fleet.storefront.domain.order.TerminalId;

import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.List;
import java.util.Objects;
import java.util.SortedMap;
import java.util.TreeMap;

/**
 * Checkout request from a terminal. Prices are never accepted from the client; only SKUs and
 * quantities. The idempotency key is generated by the terminal once per logical checkout and
 * reused verbatim on every retry.
 */
public record PlaceOrderCommand(TerminalId terminalId, String idempotencyKey, List<Item> items) {

    public PlaceOrderCommand {
        Objects.requireNonNull(terminalId, "terminalId");
        IdempotentCommand.requireKey(idempotencyKey);
        items = List.copyOf(Objects.requireNonNull(items, "items"));
        if (items.isEmpty()) {
            throw new IllegalArgumentException("An order needs at least one item");
        }
    }

    public record Item(Sku sku, Quantity quantity) {
        public Item {
            Objects.requireNonNull(sku, "sku");
            Objects.requireNonNull(quantity, "quantity");
        }
    }

    /** Items with repeated SKUs summed up, in SKU order. */
    public SortedMap<Sku, Quantity> mergedItems() {
        SortedMap<Sku, Quantity> merged = new TreeMap<>();
        for (Item item : items) {
            merged.merge(item.sku(), item.quantity(), Quantity::plus);
        }
        return merged;
    }

    /**
     * Canonical hash of the request content, used to detect a key being reused for a different
     * basket. Insensitive to item order and to splitting one SKU across several items.
     */
    public String fingerprint() {
        StringBuilder canonical = new StringBuilder();
        mergedItems().forEach((sku, qty) -> canonical.append(sku.value()).append('=').append(qty.value()).append(';'));
        try {
            byte[] hash = MessageDigest.getInstance("SHA-256").digest(canonical.toString().getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(hash);
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException(e);
        }
    }
}
